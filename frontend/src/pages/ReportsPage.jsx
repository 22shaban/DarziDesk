import { useEffect, useState } from 'react'
import jsPDF from 'jspdf'

import ReportCard from '../components/reports/ReportCard'
import ReportEmptyState from '../components/reports/ReportEmptyState'
import ReportFilters from '../components/reports/ReportFilters'

import { getOrders } from '../services/ordersApi'
import { getCustomers } from '../services/customersApi'
import { getInvoices } from '../services/invoiceApi'
import { getInventory } from '../services/inventoryApi'

import './ReportsPage.css'

function ReportsPage() {
  const [stats, setStats] = useState({
    revenue: 0,
    orders: 0,
    customers: 0,
    inventory: 0,
  })

  useEffect(() => {
    loadReportData()
  }, [])

  async function loadReportData() {
    try {
      const [
        orders,
        customers,
        invoices,
        inventory,
      ] = await Promise.all([
        getOrders(),
        getCustomers(),
        getInvoices(),
        getInventory(),
      ])

      const revenue = invoices.reduce(
        (sum, invoice) =>
          sum + Number(invoice.totalAmount || 0),
        0
      )

      setStats({
        revenue,
        orders: orders.length,
        customers: customers.length,
        inventory: inventory.length,
      })
    } catch (error) {
      console.error(error)
    }
  }

  function exportPDF() {
    const doc = new jsPDF()

    let y = 20

    doc.setFontSize(20)
    doc.text("King's Men House", 20, y)

    y += 10

    doc.setFontSize(14)
    doc.text("Business Report", 20, y)

    y += 10

    doc.setDrawColor(180)
    doc.line(20, y, 190, y)

    y += 10

    doc.setFontSize(11)

    doc.text(
      `Report Date: ${new Date().toLocaleDateString()}`,
      20,
      y
    )

    y += 12

    doc.text(`Total Revenue : Rs. ${stats.revenue}`, 20, y)
    y += 10

    doc.text(`Total Orders : ${stats.orders}`, 20, y)
    y += 10

    doc.text(`Total Customers : ${stats.customers}`, 20, y)
    y += 10

    doc.text(`Inventory Items : ${stats.inventory}`, 20, y)

    y += 15

    doc.setFontSize(14)
    doc.text("Business Summary", 20, y)

    y += 10

    doc.setFontSize(11)

    doc.text(
      `• Revenue Generated : Rs. ${stats.revenue}`,
      25,
      y
    )

    y += 8

    doc.text(
      `• Total Orders : ${stats.orders}`,
      25,
      y
    )

    y += 8

    doc.text(
      `• Total Customers : ${stats.customers}`,
      25,
      y
    )

    y += 8

    doc.text(
      `• Inventory Items : ${stats.inventory}`,
      25,
      y
    )

    y += 20

    doc.setDrawColor(180)
    doc.line(20, y, 190, y)

    y += 10

    doc.setFontSize(10)
    doc.text(
      "Generated by DarziDesk Tailor Shop Management System",
      20,
      y
    )

    doc.save("Business_Report.pdf")
  }

  return (
    <section className="reports-page">

      <div className="d-flex justify-content-between align-items-center mb-4">

        <div>

          <h1 className="mb-1">Reports</h1>

          <p className="text-muted">
            View your tailor shop business insights.
          </p>

        </div>

        <button
          className="btn btn-success"
          onClick={exportPDF}
        >
          Export PDF
        </button>

      </div>

      <ReportFilters />

      <div className="row g-3 mb-4">

        <div className="col-md-3">
          <ReportCard
            title="Revenue"
            value={`₹${stats.revenue.toLocaleString()}`}
            color="success"
          />
        </div>

        <div className="col-md-3">
          <ReportCard
            title="Orders"
            value={stats.orders}
            color="primary"
          />
        </div>

        <div className="col-md-3">
          <ReportCard
            title="Customers"
            value={stats.customers}
            color="warning"
          />
        </div>

        <div className="col-md-3">
          <ReportCard
            title="Inventory"
            value={stats.inventory}
            color="info"
          />
        </div>

      </div>

      <div className="reports-preview-card p-4">

        <h4 className="mb-3">
          Business Summary
        </h4>

        {stats.orders === 0 ? (

          <ReportEmptyState
            title="No reports available."
            message="Start adding orders to generate analytics."
          />

        ) : (

          <div className="row">

            <div className="col-md-6">

              <ul className="list-group">

                <li className="list-group-item d-flex justify-content-between">
                  <strong>Total Revenue</strong>
                  <span>₹{stats.revenue.toLocaleString()}</span>
                </li>

                <li className="list-group-item d-flex justify-content-between">
                  <strong>Total Orders</strong>
                  <span>{stats.orders}</span>
                </li>

                <li className="list-group-item d-flex justify-content-between">
                  <strong>Total Customers</strong>
                  <span>{stats.customers}</span>
                </li>

                <li className="list-group-item d-flex justify-content-between">
                  <strong>Inventory Items</strong>
                  <span>{stats.inventory}</span>
                </li>

              </ul>

            </div>

            <div className="col-md-6">

              <div className="alert alert-primary">

                <h5>Shop Performance</h5>

                <p className="mb-0">
                  Your shop currently has{" "}
                  <strong>{stats.orders}</strong> orders,
                  <strong> {stats.customers}</strong> customers and total
                  revenue of{" "}
                  <strong>
                    ₹{stats.revenue.toLocaleString()}
                  </strong>.
                </p>

              </div>

            </div>

          </div>

        )}

      </div>

    </section>
  )
}

export default ReportsPage