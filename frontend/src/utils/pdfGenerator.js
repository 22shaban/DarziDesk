import { jsPDF } from "jspdf";

export function generateInvoicePDF(invoice, shop) {
  const doc = new jsPDF();

  // Load shop settings
 const shopName =
  shop?.shopName || "DarziDesk";

const ownerName =
  shop?.ownerName || "";

const phone =
  shop?.phone || "";

const email =
  shop?.email || "";

const address =
  shop?.address || "";
  // Header
  doc.setFontSize(22);
  doc.setTextColor(33, 37, 41);
  doc.text(shopName, 20, 20);

  doc.setFontSize(11);
  doc.setTextColor(100);

  let headerY = 28;

  if (ownerName) {
    doc.text(`Owner: ${ownerName}`, 20, headerY);
    headerY += 6;
  }

  if (phone) {
    doc.text(`Phone: ${phone}`, 20, headerY);
    headerY += 6;
  }

  if (email) {
    doc.text(`Email: ${email}`, 20, headerY);
    headerY += 6;
  }

  if (address) {
    doc.text(address, 20, headerY);
    headerY += 6;
  }

  doc.line(20, headerY + 4, 190, headerY + 4);

  // Invoice Title
  doc.setFontSize(18);
  doc.setTextColor(0);
  doc.text("Invoice", 20, headerY + 18);

  doc.setFontSize(11);

  let y = headerY + 32;

  const rows = [
    ["Invoice ID", invoice.invoiceId || "-"],
    ["Order ID", invoice.orderId || "-"],
    ["Customer", invoice.customerName || "-"],
    ["Total Amount", `Rs. ${invoice.totalAmount || 0}`],
    ["Advance Paid", `Rs. ${invoice.advancePaid || 0}`],
    ["Remaining Amount", `Rs. ${invoice.remainingAmount || 0}`],
    ["Payment Status", invoice.paymentStatus || "-"],
    [
      "Generated On",
      new Date().toLocaleDateString(),
    ],
  ];

  rows.forEach(([label, value]) => {
    doc.setFont(undefined, "bold");
    doc.text(label, 20, y);

    doc.setFont(undefined, "normal");
    doc.text(String(value), 80, y);

    y += 12;
  });

  doc.line(20, y + 8, 190, y + 8);

  doc.setFontSize(12);
  doc.setTextColor(80);

  doc.text(
    "Thank you for choosing our tailoring services!",
    20,
    y + 22
  );

  doc.setFontSize(10);

  doc.text(
    "Generated by DarziDesk",
    20,
    y + 32
  );

  doc.save(
    `Invoice_${invoice.invoiceId || "invoice"}.pdf`
  );
}