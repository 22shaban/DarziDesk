import { jsPDF } from "jspdf";

export function generateReportPDF(stats, shop) {
  const doc = new jsPDF();

  const logoBase64 = shop?.logoBase64 || "";

  const shopName = shop?.shopName || "DarziDesk";
  const ownerName = shop?.ownerName || "";
  const phone = shop?.phone || "";
  const email = shop?.email || "";
  const address = shop?.address || "";

  // ==========================
  // Header
  // ==========================

  let headerY = 20;

  if (logoBase64) {
    try {
      doc.addImage(
        logoBase64,
        "PNG",
        20,
        15,
        28,
        28
      );
    } catch (error) {
      console.error("Failed to add logo:", error);
    }
  }

  doc.setFontSize(22);
  doc.setTextColor(33, 37, 41);
  doc.text(shopName, 55, 23);

  doc.setFontSize(11);
  doc.setTextColor(100);

  headerY = 30;

  if (ownerName) {
    doc.text(`Owner: ${ownerName}`, 55, headerY);
    headerY += 6;
  }

  if (phone) {
    doc.text(`Phone: ${phone}`, 55, headerY);
    headerY += 6;
  }

  if (email) {
    doc.text(`Email: ${email}`, 55, headerY);
    headerY += 6;
  }

  if (address) {
    const lines = doc.splitTextToSize(address, 120);

    doc.text(lines, 55, headerY);

    headerY += lines.length * 6;
  }

  doc.line(20, headerY + 4, 190, headerY + 4);

  // ==========================
  // Report Title
  // ==========================

  doc.setFontSize(18);
  doc.setTextColor(0);
  doc.text("Business Report", 20, headerY + 18);

  doc.setFontSize(11);

  let y = headerY + 32;

  const rows = [
    ["Report Date", new Date().toLocaleDateString()],
    ["Total Revenue", `Rs. ${stats.revenue.toLocaleString()}`],
    ["Total Orders", stats.orders],
    ["Total Customers", stats.customers],
    ["Inventory Items", stats.inventory],
  ];

  rows.forEach(([label, value]) => {
    doc.setFont(undefined, "bold");
    doc.text(label, 20, y);

    doc.setFont(undefined, "normal");
    doc.text(String(value), 80, y);

    y += 12;
  });

  doc.line(20, y + 8, 190, y + 8);

  y += 24;

  doc.setFontSize(15);
  doc.text("Business Summary", 20, y);

  y += 12;

  doc.setFontSize(11);

  doc.text(
    `• Revenue Generated : Rs. ${stats.revenue.toLocaleString()}`,
    20,
    y
  );

  y += 10;

  doc.text(
    `• Total Orders : ${stats.orders}`,
    20,
    y
  );

  y += 10;

  doc.text(
    `• Total Customers : ${stats.customers}`,
    20,
    y
  );

  y += 10;

  doc.text(
    `• Inventory Items : ${stats.inventory}`,
    20,
    y
  );

  y += 20;

  doc.line(20, y, 190, y);

  y += 15;

  doc.setFontSize(10);
  doc.setTextColor(90);

  doc.text(
    "Generated by DarziDesk",
    20,
    y
  );

  y += 6;

  doc.text(
    "Tailor Shop Management System",
    20,
    y
  );

  doc.save(
    `Business_Report_${new Date().toLocaleDateString()}.pdf`
  );
}